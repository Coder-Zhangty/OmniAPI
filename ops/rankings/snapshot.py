"""Public display-index snapshots. No database writes or accounting dependencies.

Input rows are unscaled [unix_seconds, model_name, token_count] aggregates only.
Frozen simulated history is kept separately and must never be scaled again.
All calendar arithmetic uses Asia/Shanghai (UTC+08, no DST in this interval).
"""
from __future__ import annotations

from collections import Counter, defaultdict
from datetime import date, datetime, time, timedelta, timezone
import hashlib
import json
import math
from pathlib import Path

TZ = timezone(timedelta(hours=8))
PERIODS = {"today": 86400, "week": 7 * 86400, "month": 30 * 86400,
           "year": 365 * 86400, "all": None}
MAX_SAFE_INTEGER = 2**53 - 1


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode()


def digest(value):
    return hashlib.sha256(canonical(value)).hexdigest()


def midnight(day):
    if isinstance(day, str):
        day = date.fromisoformat(day)
    return int(datetime.combine(day, time(), TZ).timestamp())


def local_day(ts):
    return datetime.fromtimestamp(ts, TZ).date()


def iso(ts):
    return datetime.fromtimestamp(ts, TZ).isoformat()


def noise(seed, key):
    return int(hashlib.sha256(f"{seed}/{key}".encode()).hexdigest()[:12], 16) / (16**12 - 1)


def validate_raw(raw):
    assert raw["recovery"] is True, "refuse non-replica input"
    assert raw["lag_seconds"] is not None and 0 <= raw["lag_seconds"] <= 120, "replica lag"
    assert isinstance(raw["as_of"], int)
    assert raw["rows"], "empty real history"
    seen = set()
    for ts, model, tokens in raw["rows"]:
        assert isinstance(ts, int) and 0 < ts <= raw["as_of"]
        assert isinstance(model, str) and model and len(model) < 512
        assert isinstance(tokens, int) and 0 <= tokens <= MAX_SAFE_INTEGER
        assert (ts, model) not in seen, "duplicate aggregate"
        seen.add((ts, model))


def calendar_factor(day, config):
    key = day.isoformat()
    if key in config["makeup_workdays"]:
        return 1.0
    for start, end in config["holiday_ranges"]:
        if start <= key <= end:
            return 0.6
    return 0.8 if day.weekday() >= 5 else 1.0


def metadata_for(name, metadata):
    if name in metadata:
        return metadata[name]
    low = name.lower()
    for prefixes, vendor, icon in [
        (("gpt-", "o1", "o3", "o4", "chatgpt", "dall-e", "sora", "text-embedding", "whisper", "tts-"), "OpenAI", "OpenAI"),
        (("claude-",), "Anthropic", "Claude.Color"),
        (("gemini-", "gemma-"), "Google", "Gemini.Color"),
        (("deepseek-",), "DeepSeek", "DeepSeek.Color"),
        (("grok-",), "xAI", "XAI"),
        (("kimi-", "moonshot-"), "Moonshot", "Moonshot"),
        (("glm-", "cogview-"), "智谱", "Zhipu.Color"),
        (("qwen", "qwq"), "Alibaba", "Qwen.Color"),
    ]:
        if low.startswith(prefixes):
            return {"vendor": vendor, "vendor_icon": icon}
    return {"vendor": "Unknown", "vendor_icon": ""}


def freeze_history(raw, config, metadata):
    """One-time deterministic simulation; never regenerated by the timer."""
    validate_raw(raw)
    first_day = min(local_day(r[0]) for r in raw["rows"])
    start = date.fromisoformat(config["history_start"])
    assert first_day > start, "no simulated interval"
    # First complete Monday-Sunday calendar week after the first real date.
    baseline_start = first_day + timedelta(days=1)
    baseline_start += timedelta(days=(-baseline_start.weekday()) % 7)
    baseline_end = baseline_start + timedelta(days=7)
    assert midnight(baseline_end) <= raw["as_of"], "need a complete real week"
    weekly = Counter()
    for ts, model, tokens in raw["rows"]:
        if midnight(baseline_start) <= ts < midnight(baseline_end):
            weekly[metadata_for(model, metadata)["vendor"]] += tokens * config["scale"]
    baseline = sum(weekly.values()) / 7
    assert baseline > 0
    pool = config["historical_models"]
    for model in pool:
        assert model.get("source") and model.get("available_from") and model.get("vendor")
        date.fromisoformat(model["available_from"])
    rows = []
    days = (first_day - start).days
    for offset in range(days):
        day = start + timedelta(days=offset)
        remaining = days - 1 - offset
        if remaining >= 90:
            fraction = 0.01 + 0.09 * offset / max(1, days - 91)
        else:
            fraction = 0.1 * 10 ** ((90 - remaining) / 90)
        volume = round(baseline * fraction * calendar_factor(day, config)
                       * (0.9 + 0.2 * noise(config["seed"], str(day))))
        eligible = [m for m in pool if m["available_from"] <= str(day)
                    and (not m.get("available_until") or str(day) < m["available_until"])]
        assert eligible, f"no verified model for {day}"
        vendors = defaultdict(list)
        for m in eligible:
            vendors[m["vendor"]].append(m)
        # Real baseline vendor mix, renormalised across verified eligible models.
        weights = {v: max(weekly.get(v, 0), sum(weekly.values()) * 0.015) for v in vendors}
        total_weight = sum(weights.values())
        allocations = []
        for vendor, models in sorted(vendors.items()):
            # Successors gradually take over; never assign outside verified dates.
            for m in models:
                age = (day - date.fromisoformat(m["available_from"])).days
                w = min(1.0, (age + 1) / 45) * m.get("weight", 1)
                if any(n.get("predecessor") == m["name"] for n in models):
                    w *= 0.25
                allocations.append([m["name"], weights[vendor] / total_weight, w, vendor])
        vendor_weights = Counter()
        for name, vw, w, vendor in allocations:
            vendor_weights[vendor] += w
        amounts = [(name, volume * vw * w / vendor_weights[v]) for name, vw, w, v in allocations]
        rounded = {name: int(value) for name, value in amounts}
        residue = volume - sum(rounded.values())
        for name, value in sorted(amounts, key=lambda x: (-(x[1] - int(x[1])), x[0]))[:residue]:
            rounded[name] += 1
        for name, value in sorted(rounded.items()):
            # Noon anchors simulated daily rows; UI explicitly labels this interval.
            if value:
                rows.append([midnight(day) + 12 * 3600, name, value])
    result = {"schema": 1, "kind": "simulated_display_index", "scale": config["scale"],
              "seed": config["seed"], "config_sha256": digest(config),
              "start": str(start), "end_exclusive": str(first_day),
              "baseline_week": [str(baseline_start), str(baseline_end)],
              "baseline_daily_index": baseline, "rows": rows}
    result["sha256"] = digest(result)
    return result


def validate_history(history, raw, config):
    copy = {k: v for k, v in history.items() if k != "sha256"}
    assert digest(copy) == history["sha256"], "frozen history modified"
    assert history["scale"] == config["scale"] == 200
    assert history["config_sha256"] == digest(config), "history/config mismatch: review migration explicitly"
    assert history["end_exclusive"] == str(min(local_day(r[0]) for r in raw["rows"])), "real coverage changed"
    pool = {m["name"]: m for m in config["historical_models"]}
    for ts, name, tokens in history["rows"]:
        day = str(local_day(ts))
        model = pool[name]
        assert history["start"] <= day < history["end_exclusive"]
        assert model["available_from"] <= day
        assert not model.get("available_until") or day < model["available_until"]
        assert isinstance(tokens, int) and tokens > 0


def growth(current, previous):
    return (current - previous) / previous * 100 if previous > 0 else (100 if current else 0)


def ranked(totals):
    return sorted(((name, value) for name, value in totals.items() if value > 0), key=lambda x: (-x[1], x[0]))


def make_snapshot(rows, metadata, period, as_of, history):
    duration = PERIODS[period]
    end = as_of + 1
    start = end - duration if duration else midnight(history["start"])
    previous_start = start - (end - start)
    totals, previous = Counter(), Counter()
    current_rows = []
    for ts, name, value in rows:
        if start <= ts < end:
            totals[name] += value
            current_rows.append((ts, name, value))
        elif previous_start <= ts < start:
            previous[name] += value
    total = sum(totals.values())
    assert 0 <= total <= MAX_SAFE_INTEGER
    previous_ranks = {n: i + 1 for i, (n, _) in enumerate(ranked(previous))}
    models = []
    vendors, previous_vendors = Counter(), Counter()
    for n, value in previous.items():
        previous_vendors[metadata_for(n, metadata)["vendor"]] += value
    vendor_models = defaultdict(list)
    for i, (name, value) in enumerate(ranked(totals)):
        meta = metadata_for(name, metadata)
        vendor = meta["vendor"]
        row = {"rank": i + 1, "model_name": name, **meta, "category": "all", "total_tokens": value,
               "share": value / total, "growth_pct": growth(value, previous[name]) if duration else None}
        if name in previous_ranks:
            row["previous_rank"] = previous_ranks[name]
        models.append(row)
        vendors[vendor] += value
        vendor_models[vendor].append(name)
    vendor_rows = [{"rank": i + 1, "vendor": v,
                    "vendor_icon": metadata_for(vendor_models[v][0], metadata).get("vendor_icon", ""),
                    "total_tokens": value, "share": value / total,
                    "growth_pct": growth(value, previous_vendors[v]) if duration else None,
                    "models_count": len(vendor_models[v]), "top_model": vendor_models[v][0]}
                   for i, (v, value) in enumerate(ranked(vendors))]
    # Small, complete chart series, including Others, derived from this exact cube.
    seconds = 3600 if period == "today" else (86400 if period in ("week", "month") else 7 * 86400)
    anchor = midnight(local_day(start))
    if seconds == 7 * 86400:
        anchor = midnight(local_day(start) - timedelta(days=local_day(start).weekday()))
    chart_models = [m["model_name"] for m in models[:10]]
    chart_vendors = [v["vendor"] for v in vendor_rows[:5]]
    model_buckets, vendor_buckets = defaultdict(Counter), defaultdict(Counter)
    for ts, name, value in current_rows:
        bucket = anchor + ((ts - anchor) // seconds) * seconds
        model_buckets[bucket][name if name in chart_models else "其他"] += value
        vendor = metadata_for(name, metadata)["vendor"]
        vendor_buckets[bucket][vendor if vendor in chart_vendors else "其他"] += value
    # Include zero buckets without inventing usage in real gaps.
    first_bucket = anchor + ((start - anchor) // seconds) * seconds
    bucket_list = list(range(first_bucket, end, seconds))
    history_points, vendor_points = [], []
    for bucket in bucket_list:
        dt = datetime.fromtimestamp(bucket, TZ)
        label = dt.strftime("%m-%d %H:%M") if period == "today" else dt.strftime("%Y-%m-%d")
        for name in chart_models + (["其他"] if len(models) > 10 else []):
            history_points.append({"ts": iso(bucket), "label": label, "model": name,
                                   "vendor": metadata_for(name, metadata)["vendor"] if name != "其他" else "其他",
                                   "tokens": model_buckets[bucket][name]})
        bucket_total = sum(vendor_buckets[bucket].values())
        for vendor in chart_vendors + (["其他"] if len(vendor_rows) > 5 else []):
            value = vendor_buckets[bucket][vendor]
            vendor_points.append({"ts": iso(bucket), "label": label, "vendor": vendor,
                                  "tokens": value, "share": value / bucket_total if bucket_total else 0})
    history_models = [{"name": m["model_name"], "vendor": m["vendor"], "total": m["total_tokens"]} for m in models[:10]]
    if len(models) > 10:
        history_models.append({"name": "其他", "vendor": "其他", "total": sum(m["total_tokens"] for m in models[10:])})
    history_vendors = [{"name": v["vendor"], "total": v["total_tokens"], "share": v["share"]} for v in vendor_rows[:5]]
    if len(vendor_rows) > 5:
        other = sum(v["total_tokens"] for v in vendor_rows[5:])
        history_vendors.append({"name": "其他", "total": other, "share": other / total})
    movers = [{"model_name": m["model_name"], "vendor": m["vendor"], "vendor_icon": m.get("vendor_icon", ""),
               "current_rank": m["rank"], "rank_delta": m["previous_rank"] - m["rank"], "growth_pct": m["growth_pct"]}
              for m in models if duration and "previous_rank" in m and m["previous_rank"] != m["rank"]]
    return {"period": period, "total_tokens": total, "all_models_count": len(models),
            "window": {"start": iso(start), "end": iso(end), "timezone": "Asia/Shanghai",
                       "comparison_available": bool(duration and previous)},
            "display": {"label": "展示指数", "scale": 200, "unit": "INDEX",
                        "simulated_start": history["start"], "simulated_end_exclusive": history["end_exclusive"]},
            "models": models[:20], "vendors": vendor_rows,
            "top_movers": sorted((m for m in movers if m["rank_delta"] > 0), key=lambda m: (-m["rank_delta"], m["model_name"]))[:6],
            "top_droppers": sorted((m for m in movers if m["rank_delta"] < 0), key=lambda m: (m["rank_delta"], m["model_name"]))[:6],
            "models_history": {"points": history_points, "models": history_models, "buckets": len(bucket_list)},
            "vendor_share_history": {"points": vendor_points, "vendors": history_vendors, "buckets": len(bucket_list)}}


def validate_snapshot(snapshot):
    total = snapshot["total_tokens"]
    assert total == sum(m["total"] for m in snapshot["models_history"]["models"])
    assert total == sum(p["tokens"] for p in snapshot["models_history"]["points"])
    assert total == sum(v["total_tokens"] for v in snapshot["vendors"])
    assert total == sum(v["total"] for v in snapshot["vendor_share_history"]["vendors"])
    assert total == sum(p["tokens"] for p in snapshot["vendor_share_history"]["points"])
    if total:
        assert math.isclose(sum(v["share"] for v in snapshot["vendors"]), 1, abs_tol=1e-12)
    for rows in (snapshot["models"], snapshot["vendors"]):
        for row in rows:
            assert isinstance(row["total_tokens"], int) and row["total_tokens"] >= 0
    for key in ("models_history", "vendor_share_history"):
        for point in snapshot[key]["points"]:
            assert isinstance(point["tokens"], int) and point["tokens"] >= 0


def generate(raw, config, metadata, history):
    validate_raw(raw)
    validate_history(history, raw, config)
    metadata = dict(metadata)
    for model in config["historical_models"]:
        metadata[model["name"]] = {"vendor": model["vendor"], "vendor_icon": model.get("vendor_icon", "")}
    scaled = [[ts, name, value * config["scale"]] for ts, name, value in raw["rows"]]
    assert sum(r[2] for r in scaled) == sum(r[2] for r in raw["rows"]) * 200
    rows = history["rows"] + scaled
    snapshots = {p: make_snapshot(rows, metadata, p, raw["as_of"], history) for p in PERIODS}
    for snapshot in snapshots.values():
        validate_snapshot(snapshot)
    version = datetime.fromtimestamp(raw["as_of"], timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + digest(snapshots)[:12]
    files = {}
    for period, snapshot in snapshots.items():
        files[period] = canonical({"success": True, "version": version, "data": snapshot})
    manifest = {"schema": 1, "version": version, "generated_at": iso(raw["as_of"]),
                "periods": {p: {"path": f"versions/{version}/{p}.json", "sha256": hashlib.sha256(content).hexdigest()}
                            for p, content in files.items()}}
    audit = {"version": version, "raw_sha256": digest(raw), "history_sha256": history["sha256"],
             "real_rows": len(raw["rows"]), "raw_tokens": sum(r[2] for r in raw["rows"]),
             "scaled_real_tokens": sum(r[2] for r in scaled), "scale": config["scale"],
             "replica_lag_seconds": raw["lag_seconds"], "config_sha256": digest(config),
             "totals": {p: s["total_tokens"] for p, s in snapshots.items()}}
    return manifest, files, audit
